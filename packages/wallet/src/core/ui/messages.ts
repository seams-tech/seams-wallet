export type WalletMessage = (typeof walletMessages)[number][0];

type LocalizedMessage = Readonly<Record<WalletLocale, string>>;

function messageEntry([en, ja]: readonly [string, string]): [string, LocalizedMessage] {
  return [en, { en, ja }];
}

const messages = new Map(walletMessages.map(messageEntry));

type MessagePattern = {
  readonly expression: RegExp;
  readonly parameters: readonly string[];
  readonly japanese: string;
};

function escapePattern(text: string): string {
  return text.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

function messagePattern([english, japanese]: readonly [string, string]): MessagePattern {
  const parameters: string[] = [];
  const parts: string[] = [];
  let offset = 0;
  for (const match of english.matchAll(/\{(\w+)\}/g)) {
    parts.push(escapePattern(english.slice(offset, match.index)), '(.+?)');
    parameters.push(match[1]);
    offset = match.index + match[0].length;
  }
  parts.push(escapePattern(english.slice(offset)));
  return { expression: new RegExp('^' + parts.join('') + '$', 's'), parameters, japanese };
}

function hasParameters(message: readonly [string, string]): boolean {
  return message[0].includes('{');
}

function longestMessageFirst(
  left: readonly [string, string],
  right: readonly [string, string],
): number {
  return right[0].length - left[0].length;
}

const patterns = walletMessages.filter(hasParameters).sort(longestMessageFirst).map(messagePattern);

export function walletText(
  locale: WalletLocale,
  message: WalletMessage,
  values: Readonly<Record<string, string | number>> = {},
): string {
  const translated = messages.get(message);
  if (!translated) throw new Error('Unknown wallet message');
  let text = translated[locale];
  for (const [name, value] of Object.entries(values)) {
    text = text.split('{' + name + '}').join(String(value));
  }
  return text;
}

/** Localize SDK default display copy. Preserve application overrides and external details. */
export function walletDisplayText<T extends string | null | undefined>(
  locale: WalletLocale,
  copy: T,
): string | T {
  if (typeof copy !== 'string' || locale === 'en') return copy;
  const normalized = copy.trim();
  const exact = messages.get(normalized);
  if (exact) return exact[locale];
  const field = normalized.endsWith(':') ? messages.get(normalized.slice(0, -1)) : undefined;
  if (field) return field[locale] + '：';
  for (const pattern of patterns) {
    const match = pattern.expression.exec(normalized);
    if (!match) continue;
    let translated = pattern.japanese;
    for (const [index, parameter] of pattern.parameters.entries()) {
      translated = translated.split('{' + parameter + '}').join(match[index + 1]);
    }
    return translated;
  }
  return copy;
}
